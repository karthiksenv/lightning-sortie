import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';

await fs.mkdir('test-results',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--disable-background-timer-throttling','--disable-renderer-backgrounding','--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:5173/?dev=1');
await page.waitForFunction(()=>window.__LIGHTNING__);
await page.waitForTimeout(2500);
await page.screenshot({path:'test-results/menu.png'});
console.log('MENU',await page.evaluate(()=>window.__LIGHTNING__.snapshot()));
await page.getByRole('button',{name:'BEGIN SORTIE'}).click();
await page.keyboard.down('KeyW');await page.keyboard.down('ArrowUp');
await page.waitForTimeout(9000);
await page.keyboard.up('KeyW');await page.keyboard.up('ArrowUp');
await page.keyboard.press('KeyG');
await page.screenshot({path:'test-results/takeoff.png'});
console.log('TAKEOFF',await page.evaluate(()=>window.__LIGHTNING__.snapshot()));
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
console.log('PAUSED',await page.evaluate(()=>window.__LIGHTNING__.snapshot()));
await page.getByRole('button',{name:'RESUME FLIGHT'}).click();
await page.evaluate(()=>window.__LIGHTNING__.start('free'));
await page.waitForTimeout(2000);
await page.screenshot({path:'test-results/free-flight.png'});
console.log('FREE',await page.evaluate(()=>window.__LIGHTNING__.snapshot()));
await page.evaluate(()=>window.__LIGHTNING__.changeSetting('timeOfDay','night'));
await page.waitForTimeout(700);await page.screenshot({path:'test-results/night.png'});
console.log('ERRORS',errors);
await browser.close();
if(errors.length)process.exitCode=1;
