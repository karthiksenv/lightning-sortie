import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

await fs.mkdir('test-results',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1366,height:768},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
try {
  await page.goto('http://127.0.0.1:5173/?dev=1');
  await page.waitForFunction(()=>window.__LIGHTNING__);
  await expect(page.getByRole('button',{name:'BEGIN SORTIE'})).toBeVisible();
  await page.getByRole('button',{name:'SELECT A MISSION'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  assert.equal(await page.locator('[data-action="start"]').count(),7);
  await page.locator('[data-mission="landing"]').click();
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.missions.active.id),'landing');
  const landing=await page.evaluate(()=>{
    const g=window.__LIGHTNING__;
    g.step(35,{pitch:-1});
    const touched=g.flight.grounded&&g.missions.touchdown;
    g.step(15,{throttle:-1});
    return{touched,...g.snapshot()};
  });
  assert.equal(landing.touched,true,'The instructed descent reaches the runway');
  assert.equal(landing.mode,'result');assert.equal(landing.progress,1);assert.ok(landing.score>2500);
  await expect(page.getByRole('button',{name:'NEXT SORTIE'})).toBeVisible();
  await page.screenshot({path:'test-results/landing-complete.png',animations:'disabled'});
  await page.getByRole('button',{name:'FLY AGAIN'}).click();
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.mode),'playing');
  await page.keyboard.press('Escape');
  const before=await page.evaluate(()=>window.__LIGHTNING__.flight.position.toArray());
  await page.waitForTimeout(500);
  assert.deepEqual(await page.evaluate(()=>window.__LIGHTNING__.flight.position.toArray()),before,'Pause freezes flight');
  await page.getByRole('button',{name:'SETTINGS',exact:true}).click();
  await page.getByRole('combobox',{name:'Time of day'}).selectOption('night');
  await page.getByRole('checkbox',{name:'Invert pitch'}).check();
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.input.invertPitch),true);
  await page.getByRole('checkbox',{name:'Invert pitch'}).uncheck();
  await page.getByRole('combobox',{name:'Time of day'}).selectOption('day');
  await page.getByRole('combobox',{name:'Graphics quality'}).selectOption('low');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'RETURN TO HANGAR'}).click();
  await page.getByRole('button',{name:'FREE FLIGHT',exact:true}).click();
  await page.keyboard.press('KeyC');await page.keyboard.press('KeyC');
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.jet.visible),false,'Cockpit camera hides the exterior model');
  await page.keyboard.press('KeyC');
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.jet.visible),true);
  await page.evaluate(()=>{const g=window.__LIGHTNING__;g.setFlight({position:[-6000,0,7500],speed:220,gear:false,grounded:false});g.step(.1);});
  await expect(page.getByRole('heading',{name:'Aircraft lost'})).toBeVisible();
  await page.getByRole('button',{name:'FLY AGAIN'}).click();
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.flight.health),100);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'RETURN TO HANGAR'}).click();
  await page.getByRole('button',{name:'SELECT A MISSION'}).click();
  await page.locator('[data-mission="dogfight"]').click();
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.missions.targets.length),3);
  await page.screenshot({path:'test-results/dogfight.png'});
  await page.evaluate(()=>window.__LIGHTNING__.start('strike'));
  assert.equal(await page.evaluate(()=>window.__LIGHTNING__.missions.targets.length),5);
  await page.screenshot({path:'test-results/strike.png'});
  await page.setViewportSize({width:960,height:640});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'RETURN TO HANGAR'}).click();
  await page.screenshot({path:'test-results/laptop-menu.png',animations:'disabled'});
  await expect(page.getByRole('button',{name:'BEGIN SORTIE'})).toBeInViewport();
  assert.deepEqual(errors,[],'No browser JavaScript, shader or resource errors');
  console.log('Browser E2E passed: seven-stage menu, physical landing to score, retry, pause, settings, camera, crash recovery, combat spawns, laptop layout.');
} finally {await browser.close();}
